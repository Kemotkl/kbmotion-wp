/* Block markup for a bio. */
function kbm_trainer_bio_blocks( $raw ) {
	$out  = '';
	$list = array();
	$flush = function () use ( &$list, &$out ) {
		if ( $list ) {
			$out .= '<!-- wp:list --><ul class="wp-block-list">';
			foreach ( $list as $li ) {
				$out .= '<!-- wp:list-item --><li>' . esc_html( $li ) . '</li><!-- /wp:list-item -->';
			}
			$out .= '</ul><!-- /wp:list -->' . "\n";
			$list = array();
		}
	};
	foreach ( preg_split( '/\R/u', trim( $raw ) ) as $line ) {
		$line = trim( $line );
		if ( '' === $line ) {
			continue;
		}
		if ( 0 === strpos( $line, '* ' ) ) {
			$list[] = trim( substr( $line, 2 ) );
			continue;
		}
		$flush();
		if ( mb_strlen( $line ) < 60 && '?' === mb_substr( $line, -1 ) ) {
			$out .= '<!-- wp:heading {"level":3} --><h3 class="wp-block-heading">' . esc_html( $line ) . '</h3><!-- /wp:heading -->' . "\n";
		} else {
			$out .= '<!-- wp:paragraph --><p>' . esc_html( $line ) . '</p><!-- /wp:paragraph -->' . "\n";
		}
	}
	$flush();
	return $out;
}

/* Short teaser for the trainer card: first sentence(s) up to ~170 characters. */
function kbm_trainer_bio_teaser( $raw ) {
	$first = trim( strtok( trim( $raw ), "\n" ) );
	if ( mb_strlen( $first ) <= 190 ) {
		return $first;
	}
	$cut = mb_substr( $first, 0, 170 );
	return rtrim( mb_substr( $cut, 0, (int) mb_strrpos( $cut, ' ' ) ), ' ,;–-' ) . '…';
}

